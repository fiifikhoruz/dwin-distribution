const fs = require('node:fs'), ts = require('typescript'), assert = require('node:assert/strict'), cp = require('node:child_process');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true,resolveJsonModule:true}}).outputText, filename);
const previousRelease = '2092bba';
const baseline = JSON.parse(cp.execFileSync('git', ['show', `${previousRelease}:lib/products.json`], {encoding:'utf8'}));
const previousOverrides = JSON.parse(cp.execFileSync('git', ['show', `${previousRelease}:lib/final-price-overrides.json`], {encoding:'utf8'}));
const additions = require('./fixtures/supplier-additions.json');
const source = require('../lib/products.json');
const overrides = require('../lib/final-price-overrides.json');
const {products, bottleSize, money} = require('../lib/catalogue.ts');
const {enquiryMessage} = require('../lib/enquiry.ts');
assert.equal(baseline.length, 1459);
assert.equal(additions.length, 16);
assert.equal(products.length, 1475);
assert.equal(new Set(products.map(p => p.id)).size, 1475, 'IDs must be unique');
assert.deepEqual(source.slice(0, baseline.length), baseline, 'Every original record and its ordering must be preserved');
assert.deepEqual(overrides, {...previousOverrides, ...Object.fromEntries(additions.map(p => [p.id, p.price]))});
for (const old of baseline) {
  const product = products.find(p => p.id === old.id);
  assert.ok(product);
  assert.equal(product.originalPrice, old.price);
  assert.equal(product.price, previousOverrides[old.id] ?? Math.round(old.price * 112 / 100), `Existing price changed: ${old.id}`);
  assert.equal(product.exactPrice, previousOverrides[old.id] ?? old.price * 112 / 100);
}
for (const expected of additions) {
  const raw = source.find(p => p.id === expected.id);
  assert.deepEqual(raw, {...expected, region:null, code:null, alc:null, qty:null, status:null, previous_price:null, updated_at:null});
  assert.deepEqual(Object.keys(raw).sort(), Object.keys(baseline[0]).sort(), 'Existing product schema retained');
  const product = products.find(p => p.id === expected.id);
  assert.equal(product.price, expected.price);
  assert.equal(product.exactPrice, expected.price);
  assert.equal(product.bottleMl, expected.size === null ? null : parseInt(expected.size, 10) * 10);
  assert.equal(product.region, 'Not specified');
  assert.equal(products.filter(p => p.name === expected.name).length, 1, 'No duplicate new names');
  const enquiry = enquiryMessage([{product, quantity:2}]);
  assert.ok(enquiry.includes(expected.name));
  assert.ok(enquiry.includes(`GHS ${money(expected.price)} each`));
  assert.ok(enquiry.includes(`GHS ${money(expected.price * 2)}`));
  assert.ok(!enquiry.includes('(code null)') && !enquiry.includes('undefined'));
}
assert.equal(products.find(p=>p.id===1085).bottleMl,1000);
assert.equal(products.find(p=>p.id===661).bottleMl,750);
assert.equal(products.find(p=>p.id===1474).bottleMl,700);
assert.equal(products.find(p=>p.id===1475).bottleMl,700);
assert.equal(bottleSize('BOTTLE 12X75CL',null),750);
assert.equal(bottleSize('BOTTLE 1.5L','150'),1500);
assert.equal(bottleSize('COFFEE 2KGS','2KGS'),null);
assert.equal(bottleSize('WINE','75'),null);
assert.equal(money(975.4),'975.40');
assert.equal(money(5797.5),'5,797.50');
assert.equal(money(29.5),'29.50');
assert.equal(money(650),'650');
const legacyMessage = enquiryMessage([{product:products[0],quantity:2}]);
assert.ok(legacyMessage.includes(`(code ${products[0].code})`));
const report = {policy:'21 supplier-final overrides, no markup; legacy pricing unchanged',baselineCommit:previousRelease,originalCount:1459,finalCount:products.length,addedCount:additions.length,unchangedExistingRecords:1459,unchangedExistingPrices:1459,previousSupplierPricesPreserved:5,supplierFinalPricesVerified:21,verifiedPrices:products.length,failures:0,additions};
fs.writeFileSync('docs/price-verification.json',JSON.stringify(report,null,2)+'\n');
console.log('PASS: 1,475 unique products; all 1,459 existing records/prices unchanged; all 21 supplier-final prices exact; names, categories, sizes, null fields and enquiries verified.');
